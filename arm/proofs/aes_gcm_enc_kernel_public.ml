(* This is the LE-band-vacuity-REPAIRED functional theorem and should be     *)
(* preferred by callers over the _CLEAN3_/_CLEAN2_/_CLEAN_/_GEN_ exports     *)
(* above.  Session 349 proved (0-hyp) that all of merge / _GEN /             *)
(* CLEAN{,2,3} are VACUOUS in the LE band (1 <= byte_len <= 64) for nonzero  *)
(* plaintext: their band-merged PRE aliases the tail "first-blocks" reads    *)
(* bt0..3 onto the head reads b0..3 (in the LE band the DIV-64 mask is 0, so *)
(* ptr0_tail = ptr0) and pins the padding blocks to zero, forcing the whole  *)
(* <=64-byte plaintext to zero — so those exports do NOT actually verify the *)
(* kernel's ct/tag output for nonzero 1..64-byte inputs.  (Wider bands were  *)
(* always sound.)                                                            *)
(*                                                                           *)
(* The FIXED theorem is a genuine 3-way band split that repairs this:        *)
(*   - LE band  (1 <= val byte_len_w <= 64): PRE re-based on the CLEAN,       *)
(*     NON-VACUOUS LE-body theorem (b0..b3 raw reads + a byte_list_at input   *)
(*     window at the TRUE byte_len width + the four head block-facts, with    *)
(*     NO aliasing bt*/ptr0_tail reads) — nonzero <=64B plaintexts ARE        *)
(*     admitted; see the companion witness lemma                             *)
(*     AES_GCM_ENC_KERNEL_FIXED_LE_ARM_PRE_NONVACUOUS.                        *)
(*   - wider band (64 < val byte_len_w): CLEAN3's PRE (sound there).          *)
(* The POST is the flat XTS-shaped shape (one aes_gcm_ct_bytes ciphertext     *)
(* window + one flat nist_ghash tag), identical across both bands.           *)
(*                                                                           *)
