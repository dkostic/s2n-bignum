(* SCOPE OF THE PUBLIC THEOREMS (updated session 321, 2026-06-27).           *)
(*                                                                           *)
(* There are TWO public re-exports here:                                      *)
(*                                                                           *)
(* 1. AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT  (control-flow; original  *)
(*    s133 re-export of AES_GCM_ENC_KERNEL_SUBROUTINE_CORRECT). It proves:    *)
(*      - the kernel terminates and returns to its caller                     *)
(*        (`read PC s = returnaddress`),                                      *)
(*      - the kernel writes only within its declared memory frame             *)
(*        (the MAYCHANGE bytes ranges over cptr / cptr_tail / xiptr /         *)
(*        ivec_ptr+12 / the 128-byte stack scratch),                          *)
(*      - the kernel preserves all callee-saved GPRs and Q-register          *)
(*        low-halves per the AAPCS64 ABI                                      *)
(*        (`MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI`).                       *)
(*    On its own this theorem does NOT pin the ciphertext or GHASH tag.       *)
(*                                                                           *)
(* 2. AES_GCM_ENC_KERNEL_AES128_FUNCTIONAL_SUBROUTINE_CORRECT  (FUNCTIONAL;   *)
(*    session 321; re-export of the C6b theorem                              *)
(*    AES_GCM_ENC_KERNEL_BYTE_LEN_LE_64_OR_64_TO_128_OR_GT_128_SUBROUTINE_    *)
(*    CTS_COLLAPSED_MEM_CORRECT in aes_gcm_enc_kernel.ml). In addition to the *)
(*    control-flow guarantees above, it pins — over the full 3-way           *)
(*    byte-length disjunction (1<=v<=64) \/ (64<v<=128) \/ (128<v):           *)
(*      - the WHOLE-INPUT ciphertext to the in-tree FIPS-197 spec, via        *)
(*        `byte_list_at (aes_gcm_ct_bytes pt_in (word_bytereverse ctr0) ks N) *)
(*           cptr (word_ushr bit_len 3) s`                                    *)
(*        where aes_gcm_ct_bytes builds on aes_gcm_ct_block_at / aes128_cipher*)
(*        (common/fips197.ml);                                                *)
(*      - the GHASH tag in Xi memory to                                       *)
(*        `word_bytereverse (nist_ghash h (word_bytereverse initial_tag)      *)
(*           [...])` (common/ghash_nist_bridge.ml / polyval_ghash.ml);        *)
(*      - the ivec+12 counter cell, with ctr0 preserved.                      *)
(*    This is the C6b functional-fidelity contract (whole-input ciphertext    *)
(*    pinning, chosen over the C6a band-guarded/first-4-blocks contract).     *)
(*                                                                           *)
(* CARRIED SCOPE-GAPS (documented antecedents / project-scope boundaries —   *)
(* NOT soundness gaps; surfaced here, not buried):                           *)
(*   - Window-derivability (CALLER OBLIGATION). The functional theorem's PRE  *)
(*     carries `LENGTH pt_in = 64`, a windowed `pt_half` invariant, and 8     *)
(*     `aes_gcm_block_at pt_in <idx> = word_bytereverse(...)` bt-facts: the   *)
(*     wider-band ciphertext is pinned THROUGH these symbolic plaintext       *)
(*     facts, not from a single clean `byte_list_at pt_in` PRE. A higher-     *)
(*     level wrapper could derive them (deferred; needs human direction).     *)
(*   - Distinct-buffer / non-in-place (debt 6). ~40 `nonoverlapping` clauses  *)
(*     incl. ptr0 vs cptr; aws-lc may encrypt in-place.                       *)
(*   - kernel != full GCM (debt 7). No AAD GHASH, no length block, no final   *)
(*     `word_xor (aes128_cipher j0 ks) tag` — those live in aws-lc C glue     *)
(*     (gcm.c), not this assembly.                                            *)
(*   - AES-128-only, encrypt-only — per the project scope cut (Goal/Strategy);*)
(*     AES-192/256 + decrypt are deferred to follow-on work.                  *)
(* ========================================================================= *)

