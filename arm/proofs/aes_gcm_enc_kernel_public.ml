(* SCOPE OF THE PUBLIC THEOREMS (updated session 354, 2026-07-23).           *)
(*                                                                           *)
(* There are SIX public re-exports here.  Two families:                       *)
(*                                                                           *)
(* 1. AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT  (control-flow; original  *)
(*    s133 re-export of AES_GCM_ENC_KERNEL_SUBROUTINE_CORRECT). It proves:    *)
(*      - the kernel terminates and returns to its caller                     *)
(*        (`read PC s = returnaddress`),                                      *)
(*      - the kernel writes only within its declared memory frame             *)
(*        (the MAYCHANGE bytes ranges over cptr / cptr_tail / xiptr /         *)
(*        ivec_ptr+12 / the 128-byte stack scratch),                          *)
(*      - the kernel preserves all callee-saved GPRs and Q-register          *)
(*        low-halves per the AAPCS64 ABI                                      *)
(*        (`MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI`).                       *)
(*    On its own this theorem does NOT pin the ciphertext or GHASH tag.       *)
(*                                                                           *)
(* 2. The FUNCTIONAL ladder — five presentation increments of the same        *)
(*    whole-input functional contract, each derived from the one below it by  *)
(*    a pure presentation layer (no re-execution, no weakening).  In addition *)
(*    to the control-flow guarantees above, they pin, at the TRUE input       *)
(*    length `LENGTH pt_in = val byte_len_w` over the full byte-length range: *)
(*      - the WHOLE-INPUT ciphertext to the in-tree FIPS-197 spec, via        *)
(*        `byte_list_at (aes_gcm_ct_bytes pt_in (word_bytereverse ctr0) ks N) *)
(*           cptr (word_ushr bit_len 3) s`                                    *)
(*        where aes_gcm_ct_bytes builds on aes_gcm_ct_block_at / aes128_cipher*)
(*        (common/fips197.ml);                                                *)
(*      - the GHASH tag in Xi memory to                                       *)
(*        `word_bytereverse (nist_ghash h (word_bytereverse initial_tag)      *)
(*           [...])` (common/ghash_nist_bridge.ml / polyval_ghash.ml).        *)
(*    The ladder, weakest presentation to strongest:                          *)
(*      _GEN     (s340): Option-1 spine-generalized 3-way band merge.         *)
(*      _CLEAN   (s345): POST collapsed to one ct window + one flat tag.       *)
(*      _CLEAN2  (s346): key-schedule reads folded; band disj -> 1<=len;      *)
(*                       dead ghost vars dropped.                             *)
(*      _CLEAN3  (s347): 45 flat nonoverlapping -> one PAIRWISE + residue.    *)
(*      _FIXED_WIN (s352): THE PREFERRED export.  LE-band-vacuity-REPAIRED     *)
(*                 (s349/s350) 3-way band split AND fully window-collapsed     *)
(*                 PRE (one `byte_list_at pt_in` window per band + an explicit *)
(*                 intrinsic over-read-zero tail obligation); the statement is *)
(*                 written LITERALLY.  New callers should use this one.        *)
(*    (Two legacy functional aliases — the C6b =64 _FUNCTIONAL_ export and the *)
(*    non-window _FIXED_ union — were deprecated and removed in s354, together *)
(*    with their now-dead MEM (non-GEN) support tower; _FIXED_WIN supersedes   *)
(*    both.)                                                                   *)
(*                                                                           *)
(* CARRIED SCOPE-GAPS (documented antecedents / project-scope boundaries —   *)
(* NOT soundness gaps; surfaced here, not buried):                           *)
(*   - Over-read tail (CALLER OBLIGATION, intrinsic). This GCM kernel reads    *)
(*     the plaintext up to a full 16B/64B block boundary past byte_len        *)
(*     (unlike XTS's exact-len read), so the _FIXED_WIN PRE carries an         *)
(*     explicit over-read-zero obligation for the [byte_len, W) tail. This is *)
(*     a faithful statement of the kernel's real memory behaviour, not a      *)
(*     weakening.  (The older _GEN/_CLEAN* exports instead carry the          *)
(*     un-collapsed symbolic plaintext-window ghost-read family.)             *)
(*   - Distinct-buffer / non-in-place (debt 6). ~40 `nonoverlapping` clauses  *)
(*     incl. ptr0 vs cptr; aws-lc may encrypt in-place.                       *)
(*   - kernel != full GCM (debt 7). No AAD GHASH, no length block, no final   *)
(*     `word_xor (aes128_cipher j0 ks) tag` — those live in aws-lc C glue     *)
(*     (gcm.c), not this assembly.                                            *)
(*   - AES-128-only, encrypt-only — per the project scope cut (Goal/Strategy);*)
(*     AES-192/256 + decrypt are deferred to follow-on work.                  *)
(* ========================================================================= *)

