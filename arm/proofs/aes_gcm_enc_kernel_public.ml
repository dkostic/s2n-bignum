(* AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT -- the single public        *)
(* export (see the top-of-file banner for the full contract).               *)
(*                                                                          *)
(* Aliased to the internal window-collapsed functional theorem              *)
(* AES_GCM_ENC_KERNEL_AES128_FUNCTIONAL_GEN_FIXED_WIN_SUBROUTINE_CORRECT    *)
(* (aes_gcm_enc_kernel.ml).  XTS-shaped PRE and POST: for every input       *)
(* length >= 1 byte it pins the whole-input ciphertext and the GHASH        *)
(* tag to the FIPS-197 / NIST-GHASH spec via a 3-way byte-length band       *)
(* split, non-vacuous in every band.  The PRE collapses the per-block       *)
(* plaintext ghost-read family to ONE input window                          *)
(* `byte_list_at pt_in ptr0 byte_len_w s` at the true byte-length width     *)
(* plus a single explicit over-read-zero obligation for the                 *)
(* [byte_len, W) tail (W = 64 in the LE band, W = aa+64 in the wider        *)
(* band).  Non-vacuity of the collapsed LE band is witnessed by             *)
(* AES_GCM_ENC_KERNEL_FIXED_LE_ARM_WIN_PRE_NONVACUOUS (nonzero <=64B pt).   *)
(*                                                                          *)
(* This name matches the .o file basename                                   *)
(* `arm/aes-gcm/aes_gcm_enc_kernel_aes128.o`, which is what the             *)
(* Makefile's explicit aes_gcm_enc_kernel_aes128.native rule (pointing      *)
(* at this file) expects.                                                   *)
(*                                                                          *)
(* Callers must also establish, beyond the standard arg-passing and         *)
(* memory-loading preconditions, the stack-vs-data nonoverlapping           *)
(* clauses (session 131/132) between cptr / cptr_tail / xiptr /             *)
(* ivec_ptr+12 and the 128-byte stack scratch                               *)
(* (word_sub stackpointer (word 128), 128).                                 *)
(*                                                                          *)
(* Name ends in `_SUBROUTINE_CORRECT` for the collect-specs.sh /            *)
(* count-proofs.sh regex.                                                   *)
(* ------------------------------------------------------------------------- *)

let AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT =
  AES_GCM_ENC_KERNEL_AES128_FUNCTIONAL_GEN_FIXED_WIN_SUBROUTINE_CORRECT;;
