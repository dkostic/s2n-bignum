(* Non-vacuity of the collapsed LE band is witnessed by                      *)
(* AES_GCM_ENC_KERNEL_FIXED_LE_ARM_WIN_PRE_NONVACUOUS (nonzero <=64B pt).     *)
(*                                                                           *)
