(*   (b) arm/proofs/specifications.txt has a named theorem to register      *)
(*       in count-proofs.sh's spec table. NOTE: collect-specs.sh collects   *)
(*       ONLY names matching the literal `_SUBROUTINE_CORRECT` (or          *)
(*       `_SUBROUTINE_SAFE`) substring, so a registered public theorem      *)
(*       MUST carry a name ending in `_SUBROUTINE_CORRECT`.                 *)
(*                                                                          *)
