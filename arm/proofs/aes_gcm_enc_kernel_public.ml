(* THE SINGLE PUBLIC EXPORT (updated session 355, 2026-07-23).              *)
(*                                                                          *)
(* AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT is the sole public          *)
(* export, mirroring the one-canonical-name convention of                   *)
(* AES_XTS_ENCRYPT_SUBROUTINE_CORRECT.  It is aliased to the fully          *)
(* window-collapsed, XTS-shaped functional theorem                          *)
(* AES_GCM_ENC_KERNEL_AES128_FUNCTIONAL_GEN_FIXED_WIN_SUBROUTINE_CORRECT    *)
(* (internal to aes_gcm_enc_kernel.ml).  Beyond the control-flow            *)
(* guarantees (the kernel terminates and returns to its caller, writes      *)
(* only within its declared memory frame, and preserves all callee-saved    *)
(* GPRs and Q-register low-halves per the AAPCS64 ABI), it pins, at the     *)
(* TRUE input length LENGTH pt_in = val byte_len_w over the full            *)
(* byte-length range (all lengths >= 1 byte; 3-way band split;              *)
(* non-vacuous in every band):                                              *)
(*   - the WHOLE-INPUT ciphertext to the in-tree FIPS-197 spec, via         *)
(*       byte_list_at (aes_gcm_ct_bytes pt_in (word_bytereverse ctr0) ks N) *)
(*         cptr (word_ushr bit_len 3) s                                     *)
(*     where aes_gcm_ct_bytes builds on aes_gcm_ct_block_at / aes128_cipher *)
(*     (common/fips197.ml);                                                 *)
(*   - the GHASH tag in Xi memory to                                        *)
(*       word_bytereverse (nist_ghash h (word_bytereverse initial_tag)      *)
(*         [...])  (common/ghash_nist_bridge.ml / polyval_ghash.ml).        *)
(*                                                                          *)
(* HISTORY: sessions 340-354 built and then collapsed a ladder of           *)
(* presentation increments (_GEN / _CLEAN / _CLEAN2 / _CLEAN3 /             *)
(* _FIXED_WIN, plus the =64 control-flow base).  Session 355                *)
(* (human-directed) reduced the six public re-exports to this single        *)
(* canonical name; the intermediate theorems all remain as internal         *)
(* lemmas in aes_gcm_enc_kernel.ml (the _FIXED_WIN derivation needs         *)
(* them) but are no longer publicly registered.                             *)
(*                                                                          *)
(* CARRIED SCOPE-GAPS (documented antecedents / project-scope               *)
(* boundaries -- NOT soundness gaps; surfaced here, not buried):            *)
(*   - Over-read tail (CALLER OBLIGATION, intrinsic). This GCM kernel       *)
(*     reads the plaintext up to a full 16B/64B block boundary past         *)
(*     byte_len (unlike XTS's exact-len read), so the PRE carries an        *)
(*     explicit over-read-zero obligation for the [byte_len, W) tail        *)
(*     (W = 64 in the LE band, W = aa+64 in the wider band).  This is a     *)
(*     faithful statement of the kernel's real memory behaviour, not a      *)
(*     weakening.                                                           *)
(*   - Distinct-buffer / non-in-place (debt 6). ~40 `nonoverlapping`        *)
(*     clauses incl. ptr0 vs cptr; aws-lc may encrypt in-place.             *)
(*   - kernel != full GCM (debt 7). No AAD GHASH, no length block, no       *)
(*     final `word_xor (aes128_cipher j0 ks) tag` -- those live in          *)
(*     aws-lc C glue (gcm.c), not this assembly.                            *)
(*   - AES-128-only, encrypt-only -- per the project scope cut (Goal);      *)
(*     AES-192/256 + decrypt are deferred to follow-on work.                *)
(* ========================================================================= *)

(* Load the standard ARM proof preamble FIRST. The aes_gcm needs-closure pulls *)
(* in common/aes.ml and common/misc.ml (via the fips197 / ghash branches), but *)
(* those files assume base.ml's preamble is already present: aes.ml uses       *)
(* WORD_RED_CONV / WORD_JOIN_CONV (Library/words.ml) and misc.ml uses SPEC1_TAC *)
(* (common/for_hollight.ml), yet neither declares the dependency. base.ml loads *)
(* Library/words.ml, common/for_hollight.ml and common/misc.ml in the right     *)
(* order (base.ml:22/31/33), so requiring it here resolves all of them at once. *)
(* The cold/interpreted gate already loads base.ml first, so this is a no-op    *)
(* there (everything "already loaded"); it only matters for the standalone      *)
(* .native build-proof.sh entry, which otherwise has no base preamble. This is  *)
(* the canonical idiom: 325 ARM proof files (incl. the sibling                  *)
(* arm/proofs/utils/aes_xts_common.ml) declare `needs "arm/proofs/base.ml"`.    *)
needs "arm/proofs/base.ml";;
needs "arm/proofs/aes_gcm_enc_kernel.ml";;

