(* Phase 11 public-facing correctness theorem for                            *)
(* aes_gcm_enc_kernel_aes128.                                                *)
(*                                                                           *)
(* This file is a thin wrapper around                                        *)
(* AES_GCM_ENC_KERNEL_SUBROUTINE_CORRECT (in arm/proofs/aes_gcm_enc_kernel.ml *)
(* line 36781). It exists so that:                                           *)
(*                                                                           *)
(*   (a) the s2n-bignum Makefile has a single proof file to drive            *)
(*       building proofs/aes_gcm_enc_kernel_aes128.native against            *)
(*       arm/aes-gcm/aes_gcm_enc_kernel_aes128.o (the AES-128 fork .o);      *)
(*                                                                           *)
(*   (b) arm/proofs/specifications.txt has a single named theorem to         *)
(*       register in count-proofs.sh's spec table.                           *)
(*                                                                           *)
(* The public theorem is `AES_GCM_ENC_KERNEL_AES128_SUBROUTINE_CORRECT` —    *)
(* a re-export of `AES_GCM_ENC_KERNEL_SUBROUTINE_CORRECT` under a name that  *)
(* matches the .o file basename convention.                                  *)
(*                                                                           *)
(* ========================================================================= *)
(* CURRENT SCOPE OF THE PUBLIC THEOREM (as of session 133, 2026-06-07):      *)
(*                                                                           *)
(* The theorem proves:                                                       *)
(*   - the kernel terminates and returns to its caller                       *)
(*     (`read PC s = returnaddress`),                                        *)
(*   - the kernel writes only within its declared memory frame               *)
(*     (the MAYCHANGE bytes ranges over cptr / cptr_tail / xiptr /           *)
(*     ivec_ptr+12 / the 128-byte stack scratch),                            *)
(*   - the kernel preserves all callee-saved GPRs and Q-register low-halves  *)
(*     per the AAPCS64 ABI (this is implicit in                              *)
(*     `MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI`).                         *)
(*                                                                           *)
(* The theorem does NOT YET prove that the produced ciphertext bytes equal   *)
(* `aes_gcm_encrypt_bytes` of the spec, nor that the produced GHASH state   *)
(* in the Xi memory equals the spec's `nist_ghash` accumulator.              *)
(*                                                                           *)
(* The kernel-level main-loop wrapper                                        *)
(* `AES_GCM_MAIN_LOOP_WRAPPER_FULL_CORRECT` (line ~8106) does carry the      *)
(* spec-level Q11 = `nist_ghash h initial_tag cts` content in its POST. The  *)
(* spec content is dropped between MAIN_LOOP_WRAPPER and the LE_64 /         *)
(* LE_64_OR_GT_128 unifier theorems used by the SUBROUTINE wrapper, because *)
(* the per-N body wrappers' POSTs were specialised to                        *)
(* `read PC s = word(pc + 0x970)` to make the LE_64 case-split close.        *)
(* Re-introducing the spec content into SUBROUTINE_CORRECT is a deferred    *)
(* "Phase 11b" piece of work.                                                *)
(* ========================================================================= *)

